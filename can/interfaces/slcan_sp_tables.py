"""
Lookup tables mirrored from MCU firmware (can_baudrate_cfg.c).

Each entry is a dict with keys: prescaler, timeSeg1, timeSeg2, sjw.
Sample point is calculated as:

    sample_point = (1 + timeSeg1) / (1 + timeSeg1 + timeSeg2)

Use ``lookup_cfg_index()`` to find the best-matching table row for a
desired sample point percentage, then pass the returned index to Bus().
"""

from typing import Dict, List, NamedTuple, Optional, Tuple


class BaudrateCfg(NamedTuple):
    prescaler: int
    timeSeg1:  int
    timeSeg2:  int
    sjw:       int

    @property
    def sample_point(self) -> float:
        """Actual sample point as a percentage (0–100)."""
        total_tq = 1 + self.timeSeg1 + self.timeSeg2
        return (1 + self.timeSeg1) / total_tq * 100.0


