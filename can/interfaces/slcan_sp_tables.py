def lookup_cfg_index(
    bitrate: int,
    target_sample_point: float,
    *,
    fd_data: bool = False,
) -> Tuple[int, BaudrateCfg]:
    """
    Find the table index whose sample point is closest to ``target_sample_point``.

    :param bitrate:
        Nominal or FD data bitrate in bit/s.
    :param target_sample_point:
        Desired sample point as a percentage, e.g. ``87.5``.
    :param fd_data:
        If ``True``, look up in ``FD_DATA_TABLES`` instead of ``BITRATE_TABLES``.

    :returns:
        ``(index, BaudrateCfg)`` — the best-matching row and its index.

    :raises KeyError:
        If ``bitrate`` is not in the relevant table dict.

    Example::

        idx, cfg = lookup_cfg_index(500_000, 87.5)
        print(f"index={idx}, actual SP={cfg.sample_point:.2f}%")
        # → index=0, actual SP=87.50%

        bus = can_slcanfd.Bus(channel="/dev/ttyUSB0",
                              bitrate=500_000,
                              bitrate_cfg_index=idx)
    """
    tables = FD_DATA_TABLES if fd_data else BITRATE_TABLES
    if bitrate not in tables:
        valid = ", ".join(str(k) for k in tables)
        raise KeyError(f"Bitrate {bitrate} not found. Available: {valid}")

    table = tables[bitrate]
    best_idx = min(
        range(len(table)),
        key=lambda i: abs(table[i].sample_point - target_sample_point),
    )
    return best_idx, table[best_idx]
